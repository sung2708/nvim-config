-- Invoked by install.sh/install.ps1 after system tools are available.
local root = vim.fn.fnamemodify(debug.getinfo(1, "S").source:sub(2), ":p:h:h")
vim.opt.rtp:prepend(root)
local function run(command)
    local result = vim.system(command, { text = true }):wait(120000)
    assert(result.code == 0, table.concat(command, " ") .. ": " .. (result.stderr or "failed"))
    return vim.trim(result.stdout or "")
end

local setup_errors = {}
local notify = vim.notify
vim.notify = function(message, level, opts)
    if level == vim.log.levels.ERROR then
        setup_errors[#setup_errors + 1] = tostring(message)
    end
    return notify(message, level, opts)
end
local lock_lines = vim.fn.readfile(root .. "/lazy-lock.json")
local ok, err = xpcall(function()
    assert(vim.fn.has("nvim-0.12") == 1, "Neovim 0.12+ is required")
    local java = assert(vim.env.SUNGP_INSTALL_JAVA_HOME, "Run bin/install.sh or bin/install.ps1 first")
    local path = assert(vim.env.SUNGP_INSTALL_PATH)
    local python = assert(vim.env.SUNGP_INSTALL_PYTHON)
    local separator = vim.fn.has("win32") == 1 and ";" or ":"
    for _, directory in ipairs(vim.split(path, separator, { plain = true, trimempty = true })) do
        assert(vim.fn.isdirectory(directory) == 1, "Toolchain directory is missing: " .. directory)
    end
    local lines = {
        "-- Generated by the installer. Put personal overrides in config/local.lua.",
        ("vim.env.JAVA_HOME = %q"):format(java),
        "vim.g.sungp_toolchain_paths = " .. vim.inspect(vim.split(path, separator, { plain = true, trimempty = true })),
        ("vim.env.PATH = %q .. %q .. (vim.env.PATH or '')"):format(path, separator),
        ("vim.g.python3_host_prog = %q"):format(python),
    }
    assert(vim.fn.filereadable(python) == 1, "Python provider missing: " .. python)
    assert(
        vim.uv.fs_realpath(root) == vim.uv.fs_realpath(vim.fn.stdpath("config")),
        "Installer config directory does not match stdpath(config)"
    )
    vim.fn.writefile(vim.split(table.concat(lines, "\n"), "\n", { plain = true }), root .. "/lua/config/toolchain.lua")
    -- The installer waits for parsers explicitly instead of starting background jobs.
    package.loaded["integrations.treesitter"] = {}
    vim.o.loadplugins = true
    require("config")
    assert(vim.fn.executable("tree-sitter") == 1, "Tree-sitter CLI missing")
    assert(run({ "tree-sitter", "--version" }):find("0.26.11", 1, true), "Tree-sitter CLI 0.26.11 required")
    local version = vim.system({ (vim.env.JAVA_HOME or java) .. "/bin/java", "-version" }, { text = true }):wait(15000)
    local major = tonumber((version.stderr or ""):match('version "(%d+)'))
    assert(version.code == 0 and major and major >= 25, "JDK 25+ is required by the configured jdtls")

    local lazy = require("lazy")
    if arg[1] == "--plugins" then
        lazy.install({ wait = true, show = false })
        vim.fn.writefile(lock_lines, root .. "/lazy-lock.json")
        lazy.restore({ wait = true, show = false })
    end
    local plugins = require("lazy.core.config").plugins
    local lock = vim.json.decode(table.concat(lock_lines, "\n"))
    for name, plugin in pairs(plugins) do
        if not plugin.virtual then
            assert(vim.fn.isdirectory(plugin.dir) == 1, "Plugin missing: " .. name)
            if lock[name] then
                assert(
                    run({ "git", "-C", plugin.dir, "rev-parse", "HEAD" }) == lock[name].commit,
                    "Plugin not at locked commit: " .. name
                )
            end
        end
    end

    if arg[1] == "--plugins" then
        print("Locked plugins installed; runtime setup continues in a fresh Neovim process")
        return
    end

    lazy.load({ plugins = { "mason.nvim", "nvim-lspconfig", "mason-tool-installer.nvim" } })
    local registry = require("mason-registry")
    local refreshed
    registry.refresh(function(success)
        refreshed = success
    end)
    assert(vim.wait(120000, function()
        return refreshed ~= nil
    end) and refreshed, "Mason registry refresh failed")
    local opts = require("lazy.core.plugin").values(plugins["mason-tool-installer.nvim"], "opts", false)
    local names = { debugpy = true, delve = true, codelldb = true }
    for _, tool in ipairs(opts.ensure_installed) do
        names[type(tool) == "table" and tool[1] or tool] = true
    end
    local mapping = require("mason-lspconfig.mappings").get_mason_map().lspconfig_to_package
    for _, server in ipairs(require("mason-lspconfig.settings").current.ensure_installed) do
        names[assert(mapping[server], "Unknown LSP: " .. server)] = true
    end
    local pending, failures = 0, {}
    for name in pairs(names) do
        local package = registry.get_package(name)
        if not package:is_installed() then
            pending = pending + 1
            print("Installing " .. name)
            package:install({}, function(success)
                if not success then
                    failures[#failures + 1] = name
                end
                pending = pending - 1
            end)
        end
    end
    assert(
        vim.wait(1800000, function()
            return pending == 0
        end, 100),
        "Mason installation timed out; rerun the installer"
    )
    assert(#failures == 0, "Mason installation failed: " .. table.concat(failures, ", ") .. "; inspect :MasonLog")
    for name in pairs(names) do
        assert(registry.get_package(name):is_installed(), "Tool missing: " .. name)
    end

    lazy.load({ plugins = { "nvim-treesitter", "neotest" } })
    require("config.compiler")
    local treesitter = require("nvim-treesitter")
    treesitter.setup()
    for _, method in ipairs({ "install", "update" }) do
        local finished, parser_error = false, nil
        treesitter[method](require("config.parsers"), { max_jobs = 4 }):await(function(e, success)
            parser_error = e or (success == false and "Parser build failed" or nil)
            finished = true
        end)
        assert(
            vim.wait(1800000, function()
                return finished
            end, 100),
            "Treesitter installation timed out"
        )
        assert(not parser_error, tostring(parser_error))
    end
    local installed = treesitter.get_installed("parsers")
    for _, parser in ipairs(require("config.parsers")) do
        assert(vim.tbl_contains(installed, parser), "Parser missing: " .. parser)
        assert(vim.treesitter.language.add(parser), "Parser cannot be loaded: " .. parser)
    end

    local junit = require("neotest-java.default_config")
    local jar = junit.default_junit_jar_filepath:to_string()
    local checksum = require("neotest-java.util.checksum").sha256
    if vim.fn.filereadable(jar) ~= 1 or checksum(jar) ~= junit.default_junit_jar_version.sha256 then
        local v = junit.default_junit_jar_version.version
        local url = ("https://repo1.maven.org/maven2/org/junit/platform/junit-platform-console-standalone/%s/junit-platform-console-standalone-%s.jar"):format(
            v,
            v
        )
        vim.fn.mkdir(vim.fn.fnamemodify(jar, ":h"), "p")
        run({ "curl", "--fail", "--location", "--retry", "3", url, "--output", jar .. ".download" })
        assert(checksum(jar .. ".download") == junit.default_junit_jar_version.sha256, "JUnit checksum mismatch")
        assert(vim.uv.fs_rename(jar .. ".download", jar))
    end
    assert(#setup_errors == 0, table.concat(setup_errors, "\n"))
    local receipt = {
        completed_at = os.date("!%Y-%m-%dT%H:%M:%SZ"),
        neovim = tostring(vim.version()),
        java = major,
        mason = {},
        parsers = installed,
    }
    for name in pairs(names) do
        receipt.mason[name] = registry.get_package(name):get_installed_version()
    end
    local report = vim.fn.stdpath("data") .. "/nvim-config/install-report.json"
    vim.fn.mkdir(vim.fn.fnamemodify(report, ":h"), "p")
    vim.fn.writefile({ vim.json.encode(receipt) }, report)
    print("Installation verified. Report: " .. report)
end, debug.traceback)
vim.fn.writefile(lock_lines, root .. "/lazy-lock.json")
if not ok then
    io.stderr:write(tostring(err) .. "\n")
    vim.cmd.cquit(1)
end
vim.cmd.qa({ bang = true })
